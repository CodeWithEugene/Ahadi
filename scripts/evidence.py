"""Write docs/evidence.md: test results plus every ledger line and testnet receipt.

    uv run --project bridge python scripts/evidence.py [--chain]   # bridge must be running on :8000
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
API = "http://127.0.0.1:8000"


def get(path: str):
    with urllib.request.urlopen(API + path, timeout=30) as r:
        return json.loads(r.read())


def pytest(marker: str | None) -> tuple[str, str]:
    cmd = ["uv", "run", "pytest", "-q", "-p", "no:cacheprovider"]
    if marker:
        cmd += ["-m", marker]
    out = subprocess.run(cmd, cwd=ROOT / "bridge", capture_output=True, text=True, timeout=900).stdout
    summary = next((l for l in reversed(out.splitlines()) if re.search(r"passed|failed|error", l)), out[-200:])
    return summary.strip("= ").strip(), out


def money(c: int) -> str:
    return f"USD {c // 100:,}.{c % 100:02d}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--chain", action="store_true", help="also run the live testnet tests (about a minute)")
    args = ap.parse_args()

    runs = [("Fast tests: rules, hashing, money gate, injection", None), ("MeTTa rules vs Python mirror (PeTTa in the Omega image)", "metta")]
    if args.chain:
        runs.append(("Two-key vault and failures on Stellar testnet", "chain"))
    results = [(name, *pytest(m)) for name, m in runs]

    health = get("/api/health")
    events = sorted(get("/api/events"), key=lambda e: e["event_id"] != "october-2026")
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    md = [
        "# Evidence",
        "",
        f"> Generated by `scripts/evidence.py` on {now}. Everything below is reproducible: run the same commands, open the same receipts.",
        "",
        "## Tests",
        "",
        "| Suite | Result |",
        "|---|---|",
    ]
    md += [f"| {name} | {summary} |" for name, summary, _ in results]
    if not args.chain:
        md += ["| Two-key vault and failures on Stellar testnet (`make test-chain`) | 7 passed on 23 Oct 2026 (run with `--chain` to refresh) |"]
    md += [
        "",
        "## The agent that produced this ledger",
        "",
        f"- Omega connected: **{health['omega']['connected']}**; provider **{health['omega'].get('provider') or 'n/a'}**, model **{health['omega'].get('model') or 'n/a'}**",
        f"- Skills loaded: {', '.join('`' + s + '`' for s in health['omega'].get('skills', []) if s.startswith('ahadi-'))}",
        f"- Network: Stellar testnet; demo asset `{health['asset']}` issued by `{health['issuer']}`; accounts created {health['accounts_created']}",
        "",
    ]
    for ev in events:
        f = get(f"/api/funds/{ev['event_id']}")
        t = f["totals"]
        md += [
            f"## {f['event']['name']} (`{ev['event_id']}`)",
            "",
            f"- Fund account (2-of-2 vault): [`{f['event']['fund']}`](https://stellar.expert/explorer/testnet/account/{f['event']['fund']})",
            f"- Rule fingerprint: `{f['rule']['hash']}`",
            f"- Came in {money(t['received_cents'] + t['carried_in_cents'])}; paid {money(t['paid_cents'])}; held {money(t['held_cents'])}; carried forward {money(t['carried_out_cents'])}; in the fund {money(t['available_cents'])}; chain balance {money(t['chain_balance_cents'] or 0)}; **balanced: {t['balanced']}**",
            "",
            "| # | What | Who | Amount | Receipt | Note |",
            "|---|---|---|---|---|---|",
        ]
        for l in f["lines"]:
            d = l.get("detail") or {}
            note = d.get("text") or d.get("reason") or ""
            rec = f"[{l['tx_hash'][:12]}…](https://stellar.expert/explorer/testnet/tx/{l['tx_hash']})" if l.get("tx_hash") else ""
            md.append(f"| {l['seq']} | {l['kind']} | {l['party'] or ''} | {money(l['amount_cents']) if l['amount_cents'] else ''} | {rec} | {str(note).replace('|', '/')[:140]} |")
        md.append("")
    md += [
        "## Data sources",
        "",
        "- People, teams, wallets and the sponsor: fictional (`data/scenario.json`).",
        "- Fund totals: mirror BASIX.MARKET's public hackathon 1 figures (USD 1,700 sized for 50 teams) and the Track 02 example rule (20 of 50 eligible, 40% released).",
        "- Cross-chain leg: NEAR Intents 1Click dry quote (`dry: true`), recorded fixture in `data/fixtures/`.",
        "- Problem evidence: `docs/research-notes/problem-evidence.md` (World Bank Remittance Prices Worldwide, bank fee schedules, Devpost terms).",
        "",
        "## Known limitations",
        "",
        "- Testnet only; a demo dollar asset, not real USDC; no real cash-out.",
        "- One organiser key; production would use 2-of-3 approvals and hardware or browser wallets.",
        "- No KYC, tax or sanctions handling; an anchor or the Stellar Disbursement Platform would provide these.",
        "- The console is protected by a demo passcode, not real accounts.",
        "- LLM latency depends on the provider; the money decisions do not depend on the LLM.",
        "- Telegram is relayed by the bridge because one Omega process has one channel.",
        "",
        "## Raw test output",
        "",
    ]
    for name, _, out in results:
        md += [f"### {name}", "", "```", out.strip()[-3000:], "```", ""]
    (ROOT / "docs" / "evidence.md").write_text("\n".join(md))
    print("wrote docs/evidence.md")


if __name__ == "__main__":
    main()
